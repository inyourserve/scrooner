"""Tag Expert scoreboard. Run from a repo checkout root: python3 data-team/tags/tools/scoreboard.py > data-team/tags/EXPERT-SCOREBOARD.md"""
import csv, glob, re, datetime, os, sys
ACC=re.compile(r'\b\d{10}-\d{2}-\d{6}\b'); RP=re.compile(r'\bR\d{1,3}\b')
rank=list(csv.DictReader(open('data-team/tags/TAG-PRIORITY-2026-11-11.csv')))
tags={r['tag']:int(r['companies'] or 0) for r in rank}
texts=[]
for p in glob.glob('data-team/tags/cards/*.md')+glob.glob('data-team/tags/library/*.csv')+glob.glob('data-team/tags/decisions/*.md'):
    for l in open(p,encoding='utf-8',errors='ignore'): texts.append((p,l))
fc=set()
tagre={t:re.compile(r'(?<![A-Za-z])'+re.escape(t)+r'(?![A-Za-z])') for t in tags}
for p,l in texts:
    if not (ACC.search(l) and RP.search(l)): continue
    for t,rx in tagre.items():
        if t not in fc and t in l and rx.search(l): fc.add(t)
pertag=[os.path.basename(p)[:-3] for p in glob.glob('data-team/tags/cards/*.md') if os.path.basename(p)[:-3] in tags]
for t in pertag:
    s=open(f'data-team/tags/cards/{t}.md').read()
    if 'FILING-CHECKED' in s and ACC.search(s) and RP.search(s): fc.add(t)
pairs=sum(tags.values()); pc=sum(tags[t] for t in fc)
tiers=[(1,95),(96,359),(360,744)]
def tier(a,b): T=[r['tag'] for r in rank if a<=int(r['rank'])<=b]; return sum(t in fc for t in T),len(T)
q_done=q_new=0
for p in glob.glob('data-team/tags/feedback-inbox*.md'):
    for l in open(p):
        if l.startswith('| 20'):
            if re.search(r'\|\s*new\s*\|\s*$',l): q_new+=1
            else: q_done+=1
nd_open='n/a'
ndp='data-team/47-fsn-store/company_tag_map/needs_detail_r1r2.csv'; ap='data-team/tags/library/needs-detail-answers-r1r2.csv'
if os.path.exists(ndp):
    nd=list(csv.DictReader(open(ndp))); ans={(r['tag'],r['stmt'],r['source']) for r in csv.DictReader(open(ap))} if os.path.exists(ap) else set()
    nd_open=sum((r['tag'],r['stmt'],r['source']) not in ans for r in nd); nd_tot=len(nd)
cs=sum(1 for l in open('data-team/tags/CONTRADICTIONS.md') if l.startswith('| C')) if os.path.exists('data-team/tags/CONTRADICTIONS.md') else 0
rc=[l for l in open('data-team/tags/RECHECK-LOG.md') if l.startswith('| 20')] if os.path.exists('data-team/tags/RECHECK-LOG.md') else []
now=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
print(f"""# Tag Expert scoreboard (generated {now})

Founder order 2026-11-12 (relayed by Dhairya): the best SEC tag expert, measured by evidence. Bar: 744/744 ranked tags FILING-CHECKED and a daily random 20-card filing re-check with a Clopper-Pearson upper bound of 10% or less.
Generated by a script, not typed. A ranked tag counts as FILING-CHECKED when a card, library or decisions line naming the tag (whole word) carries an accession number AND an R-page reference, or its own card `cards/<tag>.md` is marked FILING-CHECKED with both.

| Measure | Value |
|---|---|
| Ranked tags with a FILING-CHECKED card | **{len(fc & set(tags))} / {len(tags)}** |
| ...ranks 1-95 / 96-359 / 360-744 | {'{}/{}'.format(*tier(1,95))} / {'{}/{}'.format(*tier(96,359))} / {'{}/{}'.format(*tier(360,744))} |
| Company × tag pairs covered (TAG-PRIORITY companies column) | {pc:,} / {pairs:,} ({100*pc/pairs:.1f}%) |
| Per-tag card files (cards/<tag>.md) | {len(pertag)} |
| Reader quirks absorbed (feedback-inbox*.md lines not 'new') | {q_done} (open: {q_new}) |
| needs_detail rows open | {nd_open}{' of '+str(nd_tot) if nd_open!='n/a' else ''} |
| Contradictions settled (CONTRADICTIONS.md) | {cs} |
| Daily 20-card re-check | retired 2026-11-12 (founder correction): replaced by the blind exam below |
""")
missing=[r for r in rank if r['tag'] not in fc]
print('## Top 30 ranked tags still without a FILING-CHECKED card\n\n| Rank | Tag | Companies |\n|---|---|---|')
for r in missing[:30]: print(f"| {r['rank']} | {r['tag']} | {r['companies']} |")

