    print(subprocess.run([sys.executable, f'{ex}/tools/exam_score.py', f'{ex}/results/blind-grade.csv', f'{ex}/results/blind-timing.csv', f'{ex}/results/dev-grade-v7.csv'], capture_output=True, text=True).stdout)

